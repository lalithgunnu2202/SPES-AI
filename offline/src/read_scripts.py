text_splitter = RecursiveCharacterTextSplitter(chunk_size=500, chunk_overlap=20)

def make_chunks(sections,start):
  final_chunks=[]
  j=start
  for section in sections:
    chunkable_txt = section['content']
    chunks = text_splitter.split_text(chunkable_txt)
    for i, chunk in enumerate(chunks):
      final_chunks.append({
          "heading": section["heading"],
          "chunk_id": j,
          "chunk" : chunk
      }
      )
      j+=1
  return final_chunks

