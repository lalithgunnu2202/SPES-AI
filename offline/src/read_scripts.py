def make_sections(content):
  sections = []

  curr_heading = None
  curr_content = []
  for line in content.split("\n"):
    if re.match(r'^(\$\.)',line.strip()):
      if curr_heading:
        sections.append({
            "heading":curr_heading,
            "content":"\n".join(curr_content).strip()
        })
      curr_heading=line.strip()
      curr_content=[]
    else:
      curr_content.append(line)

  if curr_heading:
      sections.append({
          "heading": curr_heading,
          "content": "\n".join(curr_content).strip()
      })

  return sections

