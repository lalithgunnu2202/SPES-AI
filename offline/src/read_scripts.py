def format_text(content):
  content = content.replace("'\n","\n")
  content = content.replace("'","")
  content = re.sub(r'\n{2,}', '\n\n', content)
  content = content.replace("'","")
  content = content.replace("\n \n","\n")
  content = content.strip()
  return content

