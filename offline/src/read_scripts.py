def encod_chunks(cont_to_encod,model_name):
  encoder = SentenceTransformer(model_name)

  embeddings = encoder.encode(
      cont_to_encod,
      normalize_embeddings=True,
      batch_size=32,
      show_progress_bar=True
  )
  return embeddings

